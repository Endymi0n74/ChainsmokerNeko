type APIChapter = {
    id: number;
    number: number;
    name: string;
    group: string | null;
};

/**
 * Maximum time a single image request may run once the task pool has started it. The
 * download task also bounds the whole page (queue wait included), but that outer budget
 * cannot abort the request itself: without this bound a dead image host keeps the pool
 * workers busy forever and every subsequent download of this website fails as well,
 * long after the host has recovered.
 */
const IMAGE_FETCH_TIMEOUT_MS = 15_000;

/**
 * After an image host failed at the network level, keep it marked as unreachable for this
 * grace period: the pages queued behind the failure then reject immediately (with a clear
 * message) instead of stacking new waits on a host known to be dead, and the cooldown
 * expires by itself so downloads resume as soon as the host recovers.
 */
const IMAGE_HOST_COOLDOWN_MS = 20_000;

/** Image hosts currently marked as unreachable, with the end of their cooldown period. */
const imageHostCooldowns = new Map<string, number>();

/**
 * Comix can require a user to solve its rotating-image WAF challenge before the SPA retries
 * a catalogue request. Keep the real page visible while waiting so the user can complete it.
 */
const CHALLENGE_WAIT_TIMEOUT_MS = 150_000;
const FETCH_WINDOW_TIMEOUT_MS = 180_000;
const LISTEN_TIMEOUT_MS = CHALLENGE_WAIT_TIMEOUT_MS;
const LISTEN_STEP_MS = 50;

/**
 * comix.to encrypts API responses and now requires a short-lived token generated by its own
 * page scripts. Rather than reproducing that private protocol, capture the decoded response
 * objects while the SPA handles them. The preload must run before the site's modules.
 */
const CapturePreloadScript = `
    window.__comixCapture = { payloads: [] };
    window.__comixPollUntil = (ready, timeout = ${LISTEN_TIMEOUT_MS}) => new Promise(done => {
        const started = Date.now();
        const tick = () => {
            let result = false;
            try { result = ready(); } catch { /* payload may not be complete yet */ }
            if(result || Date.now() - started >= timeout) return done(result);
            setTimeout(tick, ${LISTEN_STEP_MS});
        };
        setTimeout(tick, ${LISTEN_STEP_MS});
    });
    (() => {
        const captured = new WeakSet();
        const pending = [];
        const capture = holder => {
            if(!holder || typeof holder !== 'object' || captured.has(holder)) return;
            captured.add(holder);
            pending.push(holder);

        };
        Object.defineProperty(Object.prototype, 'items', {
            configurable: true,
            get() { return undefined; },
            set(value) {
                Object.defineProperty(this, 'items', { value, writable: true, enumerable: true, configurable: true });
                capture(this);
            },
        });
        const originalDefineProperty = Object.defineProperty;
        Object.defineProperty = function (target, key, descriptor) {
            const result = originalDefineProperty.apply(this, arguments);
            if(key === 'items' && descriptor && 'value' in descriptor) capture(target);
            return result;
        };
        setInterval(() => {
            while(pending.length) {
                const holder = pending.shift();
                try { window.__comixCapture.payloads.push(JSON.parse(JSON.stringify(holder))); } catch { /* ignore */ }
            }
        }, 50);
    })();
`;

const ScriptMangas = `
    (async () => {
        const mangasByPage = new Map();
        const state = { lastPage: 1 };
        const drain = () => {
            for(const holder of window.__comixCapture.payloads.splice(0)) {
                if(!Array.isArray(holder?.items) || !holder.items.length) continue;
                const entries = holder.items.filter(item => item && typeof item.url === 'string' && item.url.includes('/title/'));
                if(!entries.length) continue;
                const page = Number(holder.meta?.page) || 1;
                state.lastPage = Math.min(2000, Math.max(state.lastPage, Number(holder.meta?.lastPage) || (holder.meta?.hasNext ? page + 1 : page)));
                mangasByPage.set(page, entries.map(item => ({
                    id: new URL(item.url, location.origin).pathname,
                    title: String(item.title ?? '').replace(/\\s+/g, ' ').trim(),
                })).filter(item => item.id && item.title));
            }
        };
        const paginate = async page => {
            const url = new URL(location.href);
            url.searchParams.set('page', String(page));
            history.pushState(history.state, '', url);
            dispatchEvent(new PopStateEvent('popstate', { state: history.state }));
            const captured = await window.__comixPollUntil(() => (drain(), mangasByPage.has(page)));
            if(!captured) throw new Error('Comix: timed out waiting for manga page ' + page);
        };
        const firstPageCaptured = await window.__comixPollUntil(() => (drain(), mangasByPage.has(1)));
        if(!firstPageCaptured) {
            const challengeVisible = location.pathname === '/@waf/challenge' || !!document.querySelector('iframe[src*="/@waf/challenge"]');
            throw new Error(challengeVisible
                ? 'Comix: security check is visible; complete it in this window and retry'
                : 'Comix: no manga captured from the browse page after waiting for the site');
        }
        for(let page = 2; page <= state.lastPage; page++) await paginate(page);
        const seen = new Set();
        return [...mangasByPage.entries()].sort(([a], [b]) => a - b).flatMap(([, entries]) => entries).filter(item => {
            if(seen.has(item.id)) return false;
            seen.add(item.id);
            return true;
        });
    })()
`;

const ScriptChapters = `
    (async () => {
        const chapterPath = '/' + location.pathname.split('/').filter(Boolean).slice(0, 2).join('/') + '/';
        const chaptersByPage = new Map();
        const state = { lastPage: 1, payloads: 0, candidates: 0 };
        const drain = () => {
            for(const holder of window.__comixCapture.payloads.splice(0)) {
                state.payloads++;
                if(!Array.isArray(holder?.items) || !holder.meta || !holder.items.length) continue;
                state.candidates++;
                const entries = holder.items.filter(item => item && typeof item.id === 'number' && typeof item.number === 'number'
                    && typeof item.url === 'string' && item.url.includes(chapterPath));
                if(!entries.length) continue;
                const page = Number(holder.meta.page) || 1;
                state.lastPage = Math.min(2000, Math.max(state.lastPage, Number(holder.meta.lastPage) || (holder.meta.hasNext ? page + 1 : page)));
                chaptersByPage.set(page, entries.map(item => ({
                    id: item.id, number: item.number, name: item.name ?? '', group: item.group?.name ?? null,
                })));
            }
        };
        const paginate = async page => {
            const url = new URL(location.href);
            url.searchParams.set('page', String(page));
            history.pushState(history.state, '', url);
            dispatchEvent(new PopStateEvent('popstate', { state: history.state }));
            const captured = await window.__comixPollUntil(() => (drain(), chaptersByPage.has(page)));
            if(!captured) throw new Error('Comix: timed out waiting for chapter page ' + page);
        };
        const firstPageCaptured = await window.__comixPollUntil(() => (drain(), chaptersByPage.has(1)));
        if(!firstPageCaptured) {
            const challengeVisible = location.pathname === '/@waf/challenge' || !!document.querySelector('iframe[src*="/@waf/challenge"]');
            throw new Error(challengeVisible
                ? 'Comix: security check is visible; complete it in this window and retry'
                : 'Comix: no chapter captured after waiting for the site (hook=' + (typeof window.__comixCapture !== 'undefined')
                    + ', payloads=' + state.payloads + ', candidates=' + state.candidates + ', url=' + location.href + ', title=' + document.title + ')');
        }
        for(let page = 2; page <= state.lastPage; page++) await paginate(page);
        const chapters = [...chaptersByPage.entries()].sort(([a], [b]) => a - b).flatMap(([, items]) => items);
        chapters.sort((a, b) => b.number - a.number);
        return chapters;
    })()
`;

const ScriptPages = `
    (async () => {
        let images = [];
        const drain = () => {
            for(const holder of window.__comixCapture.payloads.splice(0)) {
                if(!Array.isArray(holder?.items) || holder.meta || !holder.items.length) continue;
                const urls = holder.items.map(item => item && typeof item.url === 'string' ? item.url : '').filter(Boolean);
                if(urls.length > images.length) images = urls;
            }
        };
        const captured = await window.__comixPollUntil(() => (drain(), images.length > 0));
        if(!captured || !images.length) {
            const challengeVisible = location.pathname === '/@waf/challenge' || !!document.querySelector('iframe[src*="/@waf/challenge"]');
            throw new Error(challengeVisible
                ? 'Comix: security check is visible; complete it in this window and retry'
                : 'Comix: no pages captured from the reader after waiting for the site');
        }
        return images.map(url => new URL(url, location.origin).href);
    })()
`;

AddStalledChallengeReload(/^https:\/\/(?:www\.)?comix\.to/);

const ScriptMangaTitle = `
    (() => {
        const title = document.querySelector('meta[property="og:title"]')?.getAttribute('content')?.trim();
        if(!title) throw new Error('Comix: manga title not found');
        return title;
    })()
`;

/**
 * When the browser window vanishes while the extraction script is still running (window closed
 * by the user, or destroyed by a challenge timer), the platform RESOLVES with `undefined`
 * instead of rejecting — a rejection used to take Electron down through an unhandled promise
 * (crash-safe path, commit `b50842fba`). Our scripts never resolve `undefined`, so receiving it
 * can only mean the window died mid-extraction: report that explicitly instead of letting
 * `Cannot read properties of undefined (reading 'map')` reach the download task's error tooltip.
 *
 * @param result - Value returned by the window script, possibly missing when the window died.
 * @param stage - Which extraction was interrupted, used in the user-facing message.
 */
export function RequireWindowResult<T>(result: T | undefined, stage: string): T {
    if(result === undefined || result === null) {
        throw new Error(`Comix: the ${stage} window was closed before the site returned its data — retry, and complete any security check displayed in that window first`);
    }
    return result;
}

export default class extends DecoratableMangaScraper {

    public override ValidateMangaURL(url: string): boolean {
        return /^https:\/\/(?:www\.)?comix\.to\/title\/[^/]+$/.test(url);
    }

    public override async FetchManga(provider: MangaPlugin, url: string): Promise<Manga> {
        const request = new Request(url);
        const title = RequireWindowResult(await FetchWindowPreloadScript<string>(request, CapturePreloadScript, ScriptMangaTitle, 0, 180_000), 'title');
        return new Manga(this, provider, new URL(url).pathname, title);
    }

    public constructor() {
        super('comix', 'Comix', 'https://comix.to', Tags.Media.Manga, Tags.Media.Manhwa, Tags.Media.Manhua, Tags.Language.English, Tags.Source.Aggregator);
        // The download task starts its per-page budget as soon as the page is launched,
        // queue wait included, while the pool only starts the requests one by one. A
        // throttle of 4 requests/s starved every chapter beyond ~57 pages (their tail died
        // in the queue without ever being requested); 20 requests/s keeps the pool workers
        // (4 concurrent requests, unchanged) busy enough for the largest chapters.
        this.imageTaskPool.RateLimit = new RateLimit(20, 1);
    }

    public override get Icon() {
        return icon;
    }

    public override async FetchMangas(provider: MangaPlugin): Promise<Manga[]> {
        const entries = RequireWindowResult(await FetchWindowPreloadScript<{ id: string; title: string }[]>(new Request(new URL('/browse', this.URI)), CapturePreloadScript, ScriptMangas, 750, FETCH_WINDOW_TIMEOUT_MS, true), 'catalogue');
        return entries.map(({ id, title }) => new Manga(this, provider, id, title));
    }

    public override async FetchChapters(manga: Manga): Promise<Chapter[]> {
        const chapters = RequireWindowResult(await FetchWindowPreloadScript<APIChapter[]>(new Request(new URL(manga.Identifier, this.URI)), CapturePreloadScript, ScriptChapters, 0, FETCH_WINDOW_TIMEOUT_MS, true), 'chapters');
        return chapters.map(({ id, number, name, group }) => {
            const title = [number, name && `- ${name}`, group && `[${group}]`].joinTitleSegments();
            return new Chapter(this, manga, `${manga.Identifier}/${id}-chapter-${number}`, title);
        });
    }

    public override async FetchPages(chapter: Chapter): Promise<Page[]> {
        const images = RequireWindowResult(await FetchWindowPreloadScript<string[]>(new Request(new URL(chapter.Identifier, this.URI)), CapturePreloadScript, ScriptPages, 0, FETCH_WINDOW_TIMEOUT_MS, true), 'reader');
        return images.map(image => new Page(this, chapter, new URL(image)));
    }

    /**
     * The image CDN answers HTTP 403 to any request carrying a non-empty `Referer` (hotlink protection),
     * even when the referer is the image's own origin, so the pages must be requested without any referer,
     * the same way the site's own reader loads them.
     *
     * The CDN also rotates throwaway domains: a host can drop without notice (observed on
     * `*.kkplayer.wtf`). Each request is therefore bounded on its own (see IMAGE_FETCH_TIMEOUT_MS)
     * so a dead host cannot pin the pool workers, and a host that failed at the network level is
     * put in cooldown (see IMAGE_HOST_COOLDOWN_MS) so the remaining pages fail fast instead of
     * rebuilding the queue that made downloads unreliable in the first place.
     */
    public override async FetchImage(page: Page, priority: Priority, signal: AbortSignal): Promise<Blob> {
        // NOTE: the test fixtures invoke the page fetch with a null signal: treat it as "no cancellation".
        const cancellation: AbortSignal | null = signal;
        return this.imageTaskPool.Add(async () => {
            const host = page.Link.host;
            const cooldownUntil = imageHostCooldowns.get(host) ?? 0;
            if (cooldownUntil > Date.now()) {
                throw new Error(`Image host unreachable: ${host}`);
            }
            let lastError: unknown;
            for (let attempt = 0; attempt < 2; attempt++) {
                if (cancellation?.aborted) throw new DOMException('Aborted', 'AbortError');
                const attemptSignal = new AbortController();
                const onAbort = () => attemptSignal.abort();
                cancellation?.addEventListener('abort', onAbort, { once: true });
                const timeout = await SetTimeout(() => attemptSignal.abort(), IMAGE_FETCH_TIMEOUT_MS);
                try {
                    const response = await Fetch(new Request(page.Link, { signal: attemptSignal.signal, referrerPolicy: 'no-referrer' }));
                    if (!response.ok) {
                        // The host answered: it is alive, so no cooldown (the status error is likely
                        // systematic for this URL, a blind retry would only waste the time budget).
                        throw new Error(`Image request failed with HTTP ${response.status}: ${host}`);
                    }
                    return await response.blob();
                } catch (error) {
                    if (cancellation?.aborted) throw error;
                    if (attemptSignal.signal.aborted) {
                        imageHostCooldowns.set(host, Date.now() + IMAGE_HOST_COOLDOWN_MS);
                        throw new Error(`Image host did not answer within ${IMAGE_FETCH_TIMEOUT_MS}ms: ${host}`);
                    }
                    if (!(error instanceof TypeError)) throw error;
                    // Transient network error (reset, DNS hiccup): a single immediate retry,
                    // the second consecutive failure puts the host in cooldown below.
                    lastError = error;
                } finally {
                    ClearTimeout(timeout);
                    cancellation?.removeEventListener('abort', onAbort);
                }
                if (attempt < 1) await Delay(500);
            }
            imageHostCooldowns.set(host, Date.now() + IMAGE_HOST_COOLDOWN_MS);
            throw lastError instanceof Error ? lastError : new Error(String(lastError));
        }, priority, signal ?? undefined);
    }
}
